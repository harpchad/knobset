#!/usr/bin/env python3
"""Derive the macOS icon SVG from the full-bleed master.

macOS doesn't mask app icons, so the art has to carry its own shape: Apple's
grid puts an 824 px continuous-corner rounded square (radius 185.4) in the
middle of the 1024 px canvas, with a soft shadow in the margin. macOS 26 shows
icons that don't fill that shape inside a grey tile.

Usage: macos_icon.py app-icon.svg app-icon-macos.svg
"""
import re
import sys

SIZE, BODY, RADIUS = 1024, 824, 185.4
OFFSET = (SIZE - BODY) / 2

# Continuous-corner (squircle) rounded rect, the curve UIKit and AppKit use.
# Each corner is (x, y) multiples of the radius measured from that corner.
CORNER = [
    ("L", [(1.52866471, 0.0)]),
    ("C", [(1.08849323, 0.0), (0.86840689, 0.0), (0.66993427, 0.06549600)]),
    ("L", [(0.63149399, 0.07491100)]),
    ("C", [(0.37282392, 0.16905899), (0.16906013, 0.37282401), (0.07491176, 0.63149399)]),
    ("C", [(0.0, 0.86840701), (0.0, 1.08849299), (0.0, 1.52866483)]),
]


def squircle(x0, y0, w, h, r):
    x1, y1 = x0 + w, y0 + h
    # Map corner-local (along-edge, across-edge) offsets for each corner,
    # walking clockwise from the top edge.
    corners = [
        lambda a, b: (x1 - a * r, y0 + b * r),  # top right: along top, then down
        lambda a, b: (x1 - b * r, y1 - a * r),  # bottom right
        lambda a, b: (x0 + a * r, y1 - b * r),  # bottom left
        lambda a, b: (x0 + b * r, y0 + a * r),  # top left
    ]
    d = [f"M{x0 + 1.52866483 * r:.2f} {y0:.2f}"]
    for pt in corners:
        for cmd, pts in CORNER:
            d.append(cmd + " ".join(f"{px:.2f} {py:.2f}" for px, py in (pt(a, b) for a, b in pts)))
    return " ".join(d) + "Z"


def main(src, dst):
    svg = open(src).read()
    defs = re.search(r"<defs>(.*?)</defs>", svg, re.S).group(1)
    # Everything after the full-bleed background rect is the artwork.
    bg = re.search(r'<rect width="1024" height="1024" fill="(url\(#\w+\))"/>', svg)
    art = svg[bg.end():svg.rindex("</svg>")]
    shape = squircle(OFFSET, OFFSET, BODY, BODY, RADIUS)
    scale = BODY / SIZE
    out = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE} {SIZE}"><!-- Generated by scripts/icons/macos_icon.py from app-icon.svg; edit the master. --><defs>{defs}
    <clipPath id="macclip"><path d="{shape}"/></clipPath>
    <filter id="macshadow" x="-.1" y="-.1" width="1.2" height="1.25"><feDropShadow dx="0" dy="10" stdDeviation="12" flood-opacity=".3"/></filter>
  </defs>
  <path d="{shape}" fill="{bg.group(1)}" filter="url(#macshadow)"/>
  <g clip-path="url(#macclip)"><g transform="translate({OFFSET} {OFFSET}) scale({scale})">{art}</g></g>
</svg>
"""
    open(dst, "w").write(out)


if __name__ == "__main__":
    main(*sys.argv[1:3])
