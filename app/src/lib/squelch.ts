export const toneLabel = (tenths: number) => `${Math.floor(tenths / 10)}.${tenths % 10}`;

export function squelchLabel(s: Squelch): string {
  if (s.type === "ctcss") return `CTCSS ${toneLabel(s.tenths)} Hz`;
  if (s.type === "dcs") return `DCS ${s.code}${s.inverted ? " inverted" : ""}`;
  return "Carrier";
}
